#!/usr/bin/env node
/**
 * node_modules 体积诊断脚本（GTS-Play / 任意 monorepo）
 *
 * 用法：
 *   node measure-node_modules-size.cjs top <dir> [topN]
 *     —— 列出 <dir>（如 node_modules）下每个顶层目录的体积，按大小降序
 *   node measure-node_modules-size.cjs nested <workspacesRoot> [topN]
 *     —— 扫描 <workspacesRoot>（如 packages）下各 workspace 的嵌套 node_modules 体积
 *   node measure-node_modules-size.cjs tmp <dir>
 *     —— 统计 yarn 1 临时残留目录（.xxx-xxxxx 形态）总量
 *
 * 为什么用 Node 不用 PowerShell：PowerShell 递归 Get-ChildItem 在 7GB
 * node_modules 上会超时（实测 120s timeout 挂掉），Node 同步 statSync 秒级完成。
 */
const fs = require('fs');
const path = require('path');

function dirSize(p) {
  let s = 0;
  try {
    for (const e of fs.readdirSync(p, { withFileTypes: true })) {
      const fp = path.join(p, e.name);
      if (e.isDirectory()) s += dirSize(fp);
      else s += fs.statSync(fp).size;
    }
  } catch {}
  return s;
}

const [cmd, target, topNStr] = process.argv.slice(2);
const topN = parseInt(topNStr || '15', 10);
const MB = 1e6;

if (cmd === 'top') {
  const root = target || 'D:/Github/GTS-Play/node_modules';
  const top = fs
    .readdirSync(root, { withFileTypes: true })
    .filter((e) => e.isDirectory())
    .map((e) => ({ n: e.name, s: dirSize(path.join(root, e.name)) }));
  top.sort((a, b) => b.s - a.s);
  console.log(
    'TOTAL top-level:',
    (top.reduce((a, b) => a + b.s, 0) / 1e9).toFixed(2),
    'GB'
  );
  top.slice(0, topN).forEach((t) => console.log((t.s / MB).toFixed(0) + 'MB', t.n));
} else if (cmd === 'nested') {
  const base = target || 'D:/Github/GTS-Play';
  const roots = ['packages', 'demos', 'defaults', 'asset-lib', 'mods'];
  let total = 0;
  const rows = [];
  for (const r of roots) {
    const root = path.join(base, r);
    if (!fs.existsSync(root)) continue;
    for (const sub of fs.readdirSync(root, { withFileTypes: true })) {
      const nm = path.join(root, sub.name, 'node_modules');
      if (fs.existsSync(nm)) {
        const s = dirSize(nm);
        total += s;
        rows.push({ p: r + '/' + sub.name, s });
      }
    }
  }
  rows.sort((a, b) => b.s - a.s);
  console.log(
    'nested node_modules total:',
    (total / 1e9).toFixed(2),
    'GB across',
    rows.length,
    'workspaces'
  );
  rows.slice(0, topN).forEach((r) => console.log((r.s / MB).toFixed(0) + 'MB', r.p));
} else if (cmd === 'tmp') {
  const root = target || 'D:/Github/GTS-Play/node_modules';
  const tmp = fs
    .readdirSync(root, { withFileTypes: true })
    .filter((e) => e.isDirectory() && /^\..+-\w+$/.test(e.name))
    .map((e) => ({ n: e.name, s: dirSize(path.join(root, e.name)) }));
  tmp.sort((a, b) => b.s - a.s);
  console.log(
    '.xxx 临时目录数量:',
    tmp.length,
    '总大小:',
    (tmp.reduce((a, b) => a + b.s, 0) / MB).toFixed(0) + 'MB'
  );
  tmp.slice(0, topN).forEach((t) => console.log((t.s / MB).toFixed(0) + 'MB', t.n));
} else {
  console.log('用法: node measure-node_modules-size.cjs <top|nested|tmp> [dir] [topN]');
}
